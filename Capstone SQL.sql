USE project;
-- 3. INNER JOIN for Order Details
-- Join orders, order_items, and products to display detailed line items.
SELECT o.order_id, oi.order_id, oi.product_id, p.product_id
FROM order_items oi
INNER JOIN orders o ON o.order_id = oi.order_id
INNER JOIN product p ON oi.product_id = p.product_id;
 
-- 4. Total Sales by Store
SELECT 
    o.store_id, 
    SUM(oi.total_price) AS total_sales
FROM orders o
JOIN order_items oi 
    ON o.order_id = oi.order_id
GROUP BY o.store_id;
 
-- 5. Top 5 Selling Products
-- Use ORDER BY and LIMIT to get the top 5 most sold products by quantity.
 SELECT 
    p.product_name, 
    SUM(oi.quantity) AS total_quantity_sold
FROM order_items oi
JOIN product p 
    ON oi.product_id = p.product_id
GROUP BY p.product_name
ORDER BY total_quantity_sold DESC
LIMIT 5;
 
-- 6. Customer Purchase Summary
-- For each customer, return total orders placed, total items purchased, and total revenue.
 SELECT 
    c.customer_id,
    c.first_name,
    c.last_name,
    COUNT(DISTINCT o.order_id) AS total_orders,
    SUM(oi.quantity) AS total_items_purchased,
    SUM(oi.total_price) AS total_revenue
FROM customer c
LEFT JOIN orders o 
    ON c.customer_id = o.customer_id
LEFT JOIN order_items oi 
    ON o.order_id = oi.order_id 
GROUP BY 
    c.customer_id, 
    c.first_name, 
    c.last_name;
    
-- 7. Segment Customers by Total Spend
-- Write a query to classify customers into spending brackets (e.g., low,medium, high).
 SELECT 
    c.customer_id,
    SUM(oi.total_price) AS total_spent,
    CASE
        WHEN SUM(oi.total_price) < 1000 THEN 'Low'
        WHEN SUM(oi.total_price) BETWEEN 1000 AND 3000 THEN 'Medium'
        ELSE 'High'
    END AS spending_bracket
FROM customer c
JOIN orders o ON c.customer_id = o.customer_id
JOIN order_items oi ON o.order_id = oi.order_id
GROUP BY c.customer_id
ORDER BY total_spent DESC;

-- 8. Staff Performance Analysis
-- Analyze total revenue generated by each staff member based on their handled orders.
 SELECT 
    st.staff_id,
    st.store_id,
    COUNT(DISTINCT o.order_id) AS total_orders_handled,
    SUM(oi.total_price) AS total_revenue
FROM staff st
INNER JOIN orders o ON st.staff_id = o.staff_id
INNER JOIN order_items oi ON o.order_id = oi.order_id
GROUP BY st.staff_id, st.store_id
ORDER BY total_revenue DESC;
 
-- 9. Stock Alert Query
-- Write a query to list products where stock quantity < 10 in any store.
 SELECT 
    s.store_name,
    p.product_name,
    st.quantity AS stock_quantity
FROM stocks st
INNER JOIN stores s ON st.store_id = s.store_id
INNER JOIN product p ON st.product_id = p.product_id
WHERE st.quantity < 10
ORDER BY st.quantity ASC;
 
